# AETHER//SYNTAX: the Lattice catalog (assets/lattice.txt) -> a C header of 12-bit masks, names, interval vectors.
#   tools/gen_lattice.py OUT.h
# Every object is a set of pitch classes on the ring of twelve. The header carries what the firmware needs to draw,
# name and recognise each one without working anything out at run time: its mask, its altered tones, its interval
# vector (the "charge": how many of each bond class 1..6 it holds), how many rotations map it onto itself (a "fixed
# point" of the Law of Rotation when that is under 12), and its names with sharp / flat signs as the UI font's glyphs.
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "lattice.txt"
KINDS = {"P": "AX_PARTICLE", "B": "AX_BOND", "F": "AX_FIELD", "C": "AX_BOUND"}


def signs(s):
    """'#' and 'b' after a note letter or a degree digit -> the UI font's sharp (0x80) and flat (0x81) glyphs"""
    out = []
    for i, ch in enumerate(s):
        prev = s[i - 1] if i else " "
        nxt = s[i + 1] if i + 1 < len(s) else " "
        if ch == "#" and (prev in "ABCDEFG" or prev.isdigit() or nxt.isdigit()):
            out.append('\\x80" "')               # (the string closed and reopened: no hex digit after the escape)
        elif ch == "b" and (prev in "ABCDEFG" or nxt.isdigit()) and not (prev.isalpha() and prev.islower()):
            out.append('\\x81" "')
        else:
            out.append(ch)
    return "".join(out)


def cstr(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + signs(s) + '"'


def mask_of(pcs):
    m = 0
    for p in pcs:
        m |= 1 << p
    return m


def rot(m, k):
    k %= 12
    return ((m << k) | (m >> (12 - k))) & 0xFFF


def ivec(pcs):
    v = [0] * 6
    for i, a in enumerate(pcs):
        for b in pcs[i + 1:]:
            d = (b - a) % 12
            d = min(d, 12 - d)
            v[d - 1] += 1
    return v


def period(m):
    for k in range(1, 13):
        if rot(m, k) == m:
            return k
    return 12


def parse():
    rows = []
    for ln, line in enumerate(SRC.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        f = [x.strip() for x in line.split("|")]
        while len(f) < 7:
            f.append("")
        kind, name, sym, cosmic, pcs, tier, formula = f[:7]
        if kind not in KINDS:
            raise SystemExit(f"{SRC}:{ln}: unknown kind {kind!r}")
        pc, alt = [], []
        for t in pcs.split():
            a = t.endswith("*")
            v = int(t.rstrip("*"))
            if not 0 <= v < 12:
                raise SystemExit(f"{SRC}:{ln}: pitch class {v} out of range")
            pc.append(v)
            if a:
                alt.append(v)
        if 0 not in pc and kind != "P":
            raise SystemExit(f"{SRC}:{ln}: a set is written from its root, 0")
        rows.append(dict(kind=kind, name=name, sym=sym, cosmic=cosmic, pcs=sorted(set(pc)), alt=alt,
                         tier=int(tier or 1), formula=formula, ln=ln))
    return rows


def main():
    out = Path(sys.argv[1])
    rows = parse()
    by = {k: [r for r in rows if r["kind"] == k] for k in KINDS}
    if len(by["P"]) != 12 or len(by["B"]) != 6:
        raise SystemExit("gen_lattice: 12 particles and 6 bonds expected")
    # no two fields, and no two chords, may light the same nodes from the same root (the recogniser's answer would
    # depend on the table's order)
    for k in ("F", "C"):
        seen = {}
        for r in by[k]:
            m = mask_of(r["pcs"])
            if m in seen:
                raise SystemExit(f"gen_lattice: {r['name']} and {seen[m]} are the same set")
            seen[m] = r["name"]
    L = ["/* generated by tools/gen_lattice.py from assets/lattice.txt: do not edit */",
         "#ifndef AX_LATTICE_H", "#define AX_LATTICE_H", "#include <stdint.h>", "",
         "enum { AX_PARTICLE, AX_BOND, AX_FIELD, AX_BOUND, AX_NKIND };",
         "typedef struct {",
         "    uint16_t mask;           /* the pitch classes from the root (bit 0 = the root; a particle: its own class) */",
         "    uint16_t alt;            /* .. the altered tones (drawn notched) */",
         "    uint8_t kind, tier, n;   /* AX_*, the CHALLENGE tier, how many nodes */",
         "    uint8_t period;          /* rotations that map it onto itself: under 12 = a fixed point */",
         "    uint8_t ivec[6];         /* the charge: bonds of class 1..6 inside it */",
         "    const char *name, *sym, *cosmic, *formula;",
         "} ax_obj_t;", ""]
    for k, arr in (("P", "AX_PART"), ("B", "AX_BONDS"), ("F", "AX_FIELDS"), ("C", "AX_CHORDS")):
        L.append(f"#define {arr}_N {len(by[k])}")
        L.append(f"static const ax_obj_t {arr}[{arr}_N] = {{")
        for r in by[k]:
            pcs = r["pcs"]
            m = mask_of(pcs)
            iv = ivec(pcs) if k != "P" else [0] * 6
            per = period(m) if k != "P" else 12
            L.append(f"    {{0x{m:03X}, 0x{mask_of(r['alt']):03X}, {KINDS[k]}, {r['tier']}, {len(pcs)}, {per}, "
                     f"{{{', '.join(map(str, iv))}}}, {cstr(r['name'])}, {cstr(r['sym'])}, {cstr(r['cosmic'])}, "
                     f"{cstr(r['formula'])}}},")
        L.append("};")
        L.append("")
    # a sine table for the drawing (the unit's libc has no trigonometry): 256 steps a turn, Q14
    import math
    sines = [round(16384 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
    L.append("/* sin(2 pi i / 256) in Q14 (cos: index + 64) */")
    L.append("static const int16_t AX_SIN[256] = {")
    for i in range(0, 256, 16):
        L.append("    " + ", ".join(str(v) for v in sines[i:i + 16]) + ",")
    L.append("};")
    L.append("")
    L.append("#endif")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"lattice: {len(by['P'])} particles, {len(by['B'])} bonds, {len(by['F'])} fields, "
          f"{len(by['C'])} bound states -> {out}")


if __name__ == "__main__":
    main()
